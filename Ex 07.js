// Exercise array methods
let colors = ['Red', 'Green', 'Grey', 'Yellow']

console.log(colors);
// 
console.log("After push");

colors.push('Brown')
console.log(colors);

// 
console.log("after pop")

colors.pop()
console.log(colors);

// 
console.log('After unshift')

colors.unshift('White')
console.log(colors);

// 
console.log("After shift")

colors.shift()
console.log(colors)

